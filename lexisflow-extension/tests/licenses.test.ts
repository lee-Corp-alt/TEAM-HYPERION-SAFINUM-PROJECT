import { readFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { describe, expect, it } from "vitest";

// The licence notices must cover everything that ships, and must keep doing so as dependencies change.

const root = process.cwd();
const loadGenerator = async () =>
  (await import(/* @vite-ignore */ pathToFileURL(join(root, "scripts", "licenses.mjs")).href)) as {
    collectPackages: () => { name: string; version: string; license: string; text: string | null }[];
    renderLicenseText: () => string;
  };
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf-8")) as { dependencies: Record<string, string>; scripts: Record<string, string> };

// The generator writes Unix line endings; licence files on Windows may have Windows ones.
const CRLF = String.fromCharCode(13) + String.fromCharCode(10);
const LF = String.fromCharCode(10);
const unix = (value: string) => value.split(CRLF).join(LF);

describe("third-party licence notices", () => {
  it("cover every runtime dependency in package.json, each with a licence id", async () => {
    const { collectPackages } = await loadGenerator();
    const names = new Set(collectPackages().map((p) => p.name));
    for (const dependency of Object.keys(pkg.dependencies)) expect(names, dependency).toContain(dependency);
    for (const p of collectPackages()) expect(p.license, p.name).not.toMatch(/UNKNOWN|UNLICENSED/);
  });

  it("carry the full licence text for each package that has one", async () => {
    const { collectPackages, renderLicenseText } = await loadGenerator();
    const text = renderLicenseText();
    for (const p of collectPackages().filter((p) => p.text)) expect(text, p.name).toContain(unix(p.text!).slice(0, 120));
    expect(text).toContain("MIT License");
    expect(text).toContain("SIL OPEN FONT LICENSE");
  });

  it("say that no voice model or speech engine is shipped, and point to the source code", async () => {
    const text = (await loadGenerator()).renderLicenseText();
    expect(text).toMatch(/ships no voice model, no speech engine/);
    expect(text).toMatch(/Web Speech API/);
    expect(text).toMatch(/complete source code of LexisFlow itself/);
    expect(text).not.toMatch(/Kokoro|eSpeak|ephone|onnxruntime/);
  });

  it("leave out what is never shipped: Node-only image libraries and type declarations", async () => {
    const text = (await loadGenerator()).renderLicenseText();
    expect(text).not.toMatch(/libvips|@img\/sharp|onnxruntime|@types\//);
  });

  it("are regenerated by every build", () => {
    expect(pkg.scripts.postbuild).toMatch(/licenses\.mjs/);
  });
});
